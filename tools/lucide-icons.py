#!/usr/bin/env python3
"""Vendor Lucide's line icons into the app — the chrome, and only the chrome.

    npm install --no-save lucide-static && python3 tools/lucide-icons.py

The category markers are no longer Lucide's. The owner wanted solid glyphs, and
Lucide is a line-only family, so ``tools/phosphor-icons.py`` owns those now — it
writes both clients' marker tables from Phosphor's ``fill`` weight. What is left
here is the chrome: the rail, the buttons, the browser's arrows. Line art is
deliberate there — a screenful of filled buttons would shout as loudly as the
content they sit under, and the markers are the things that have to be found at a
glance.

One family, one 24px grid, one stroke weight, each icon exactly as Lucide draws
it. The chrome module is generated whole; do not hand-edit it — change the mapping
here and re-run.
"""

from __future__ import annotations

import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
ICON_DIR = REPO / "node_modules" / "lucide-static" / "icons"
APP_UI_ICONS = REPO / "frontend" / "src" / "lib" / "ui-icons.tsx"

# The chrome around the markers — the rail, the buttons, the browser's arrows.
# Written as a finished file rather than spliced: it is generated whole.
CHROME = {
    "HouseIcon": "house",
    "SettingsIcon": "settings",
    "PlusIcon": "plus",
    "ChevronRightIcon": "chevron-right",
    "ChevronLeftIcon": "chevron-left",
    "CheckIcon": "check",
    "XIcon": "x",
    "BackIcon": "arrow-left",
    "ReceiptIcon": "receipt-text",
}


def shapes_of(name: str) -> str:
    """The icon's shapes, on one line, with Lucide's own attributes kept."""
    file = ICON_DIR / f"{name}.svg"
    if not file.exists():
        raise SystemExit(
            f"missing {file} — run: npm install --no-save lucide-static"
        )
    markup = file.read_text(encoding="utf-8")
    # Past the <svg ...> tag (the file opens with an @license comment) to the end
    # of the element: the shapes only. The root tag carries the theme — viewBox,
    # fill="none", stroke="currentColor", stroke-width="2", round caps — and the
    # component's own <svg> repeats it, so the two cannot disagree.
    open_tag = markup.index("<svg")
    inner = markup[markup.index(">", open_tag) + 1 : markup.rindex("</svg>")]
    return re.sub(r"\s+", " ", inner).strip()


def ui_icons_source() -> str:
    blocks = "\n\n".join(
        f'''/** Lucide's `{name}`. */
export function {component}({{
  className,
  strokeWidth = 2,
}}: IconProps) {{
  return (
    <svg
      className={{className}}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={{strokeWidth}}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      dangerouslySetInnerHTML={{{{ __html: '{shapes_of(name)}' }}}}
    />
  )
}}'''
        for component, name in CHROME.items()
    )
    return f'''/**
 * The chrome icons: the rail, the buttons, the browser's own arrows.
 *
 * **Generated by `tools/lucide-icons.py`** from `lucide-static` — Lucide
 * (lucide.dev, ISC licence), one 24px grid at one stroke weight. The category
 * markers are a separate, solid family (`icons.tsx`, Phosphor's `fill` weight):
 * the chrome stays line art so the things you tap and the things you read do not
 * compete. Do not hand-edit; change the mapping in that script and re-run it.
 */

type IconProps = {{
  className?: string
  /** Lucide's own weight; nobody in this file thins the family's line. */
  strokeWidth?: number
}}

{blocks}
'''


def main() -> int:
    if not ICON_DIR.exists():
        print(
            f"{ICON_DIR} is missing — run: npm install --no-save lucide-static",
            file=sys.stderr,
        )
        return 1

    APP_UI_ICONS.write_text(ui_icons_source())
    print(
        f"  {APP_UI_ICONS.relative_to(REPO)}  {len(CHROME)} chrome icons"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
