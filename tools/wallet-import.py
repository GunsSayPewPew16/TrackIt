FALLBACK_SLUG = "unknown"

# The labels Wallet repeats across sets, pointing at the row the export itself
# uses. Only the ones this export actually has a document for need an entry.
EXPORT_LABELS = {
    "Child Support": "child-support",
}

# The account a row belongs to when the export (or a hand-written row) does not
# say. UPI is the owner's main account: 115 of the 122 imported rows are on it.
FALLBACK_ACCOUNT = "upi"


def account_slug(name: str) -> str:
    """"UPI" -> "upi", "Cash" -> "cash": a stable id from the owner's own name."""
    slug = "".join(c if c.isalnum() else "-" for c in name.lower()).strip("-")
    return slug or FALLBACK_ACCOUNT


def js_str(value: str) -> str:
    """A double-quoted TS string literal, the app's own house style."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def slug_for(wallet_name: str, slug_by_name: dict[str, str]) -> str:
    """Map an export category name onto a TrackIt id, loudly if it is new."""
    slug = slug_by_name.get(wallet_name)
    if slug is None:
        print(f"  ! unknown category {wallet_name!r} -> {FALLBACK_SLUG}", file=sys.stderr)
        return FALLBACK_SLUG
    return slug


def local_date(iso: str, tz: timezone) -> str:
    """`2026-10-08T18:33:21.773Z` -> `2026-10-09` in the given offset."""
    stamp = iso.replace("Z", "+00:00")
    return datetime.fromisoformat(stamp).astimezone(tz).date().isoformat()


def local_moment(iso: str, tz: timezone) -> int:
    """The same moment as epoch milliseconds, which is the app's only clock.

    A row's day *and* its time come from this: the ledger cards print the clock
    ("8:05 AM") and group the day they belong to, so an import that kept only a
    date would lose half of what a card says.
    """
    stamp = iso.replace("Z", "+00:00")
    return round(datetime.fromisoformat(stamp).astimezone(tz).timestamp() * 1000)


def load_docs(path: str) -> list[dict]:
    with open(path, encoding="utf-8") as handle:
        export = json.load(handle)

    # A Wallet export is `{ "<pouch user>": { "by-sequence": [...] } }`.
    db = next(iter(export.values()))
    return db["by-sequence"]


def check_group_colors(
    docs: list[dict],
    group_of_slug: dict[str, str | None],
    slug_by_name: dict[str, str],
) -> tuple[int, list[str]]:
    """Prove the table's groups against the colours in the export.

    Wallet paints every subcategory with its group's colour, so a category whose
    colour maps to a different group than the table claims is either a mistake in
    the table or a Wallet that groups things differently. Either way it is worth
    saying out loud rather than grouping the owner's money silently wrong.

    Returns how many categories could be checked, and every disagreement.
    """
    checked = 0
    problems: list[str] = []
    for doc in docs:
        if doc.get("reservedModelType") != "Category" or doc.get("_deleted"):
            continue
        colour = (doc.get("color") or "").upper()
        expected = GROUP_COLORS.get(colour)
        slug = slug_by_name.get(doc["name"])
        if not colour or expected is None or slug is None:
            continue
        checked += 1
        if group_of_slug.get(slug) != expected:
            problems.append(
                f"{doc['name']} is painted {colour} (group {expected}) "
                f"but the table puts it in {group_of_slug.get(slug)}"
            )
    return checked, problems


def account_table(docs: list[dict]) -> dict[str, dict]:
    """Wallet's own accounts, keyed by the id its records point at.

    A record's ``accountId`` is the account document's ``_doc_id_rev`` without
    its revision (``-Account_<uuid>``), so that prefix is the join key.
    """
    table: dict[str, dict] = {}
    for doc in docs:
        if doc.get("reservedModelType") != "Account":
            continue
        key = doc["_doc_id_rev"].split("::")[0]
        table[key] = {
            "slug": account_slug(doc["name"]),
            "name": doc["name"],
            "opening": doc["initAmount"],
        }
    return table


def splice_array(path: Path, anchor: str, rows: list[str], expected: int) -> None:
    """Rewrite the body of an `export const NAME: T[] = [ ... ]` table."""
    text = path.read_text(encoding="utf-8")
    start = text.index(anchor) + len(anchor)  # past the anchor, so the type's own
    open_bracket = text.index("[", start)    # `[]` cannot be taken for the table
    close = re.search(r"\n\s*\];?\n", text[open_bracket:])
    assert close, f"unterminated {anchor!r} in {path}"
    end = open_bracket + close.start()  # the newline the closing bracket sits on
    assert text[open_bracket:end].count("\n") < expected + 3, (
        f"{path}: {anchor!r}'s closing bracket looks too far away — refusing"
    )
    path.write_text(text[:open_bracket] + "[\n" + "\n".join(rows) + text[end:])


def check_markers(repo_root: Path, slugs: list[str]) -> tuple[int, list[str]]:
    """Prove every category has a marker — and that no marker is orphaned.

    ``tools/lucide-icons.py`` writes that table from ``lucide-static``, and this
    is what catches it being edited afterwards, or a category being added here
    without a glyph: the fallback dot is a placeholder rather than a marker. A
    glyph left behind by a category that has since been renamed is named too — it
    is dead weight rather than a mistake, but it is the same drift. Only the
    table's shape rows are read; the component around them is not.
    """
    file = repo_root / "app/src/lib/category-icons.tsx"
    if not file.exists():
        return 0, [f"{file} is missing"]
    markup = file.read_text(encoding="utf-8")
    start = markup.index("CATEGORY_ICONS")
    close = re.search(r"\n\s*\};?\n", markup[start:])
    end = start + (close.end() if close else len(markup) - start)
    marked = dict(re.findall(r"'([^']+)':\s*'([^']+)',", markup[start:end]))

    problems: list[str] = []
    for slug in slugs:
        if slug not in marked:
            problems.append(f"{slug} has no marker")
    for slug in sorted(set(marked) - set(slugs)):
        problems.append(f"{slug} has a marker but is no longer a category")
    return len(marked), problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("export", help="wallet_unlocked_export.json")
    parser.add_argument("--app-out", default="tools/trackit-expenses.json", help="where to write the TrackIt array")
    parser.add_argument("--tz", default="+05:30", help="offset used to turn UTC recordDate into a local date")
    args = parser.parse_args()

    offset = datetime.strptime(args.tz, "%z").tzinfo if args.tz else timezone.utc
    assert offset is not None
    # Wallet repeats a handful of labels across sets — Child Support under three
    # of them, Lottery, gambling and Gifts under two — and a slug belongs to one
    # group, so the repeats carry their group in the id (`income-child-support`).
    # The export's own documents are the unqualified rows, and the rows already in
    # `trackit-expenses.json` name those slugs, so a repeat must never win a
    # name lookup: the plain table would hand "Child Support" to the Income row
    # (it is the last one), hence the explicit answer here.
    slug_by_name = {name: slug for name, slug, _, _ in CATEGORIES}
    slug_by_name.update(EXPORT_LABELS)
    label_by_slug = {slug: name for name, slug, _, _ in CATEGORIES}
    group_of_slug = {slug: group for _, slug, _, group in CATEGORIES}

    docs = load_docs(args.export)
    records = [doc for doc in docs if doc.get("reservedModelType") == "Record"]
    category_names = {
        doc["_doc_id_rev"].split("::")[0]: doc["name"]
        for doc in docs
        if doc.get("reservedModelType") == "Category"
    }
    accounts = account_table(docs)

    kept: list[dict] = []
    skipped = {"deleted": 0, "transfer": 0}
    unassigned = 0

    for record in records:
        if record.get("_deleted"):
            skipped["deleted"] += 1
            continue
        if record.get("transferId"):                      # money moved between own accounts
            skipped["transfer"] += 1
            continue
        kind = "expense" if record.get("type") == 1 else "income"

        held_by = accounts.get(record.get("accountId"))
        if held_by is None:
            unassigned += 1
            print(f"  ! account {record.get('accountId')!r} -> {FALLBACK_ACCOUNT}", file=sys.stderr)
        account = held_by["slug"] if held_by else FALLBACK_ACCOUNT

        slug = slug_for(category_names.get(record.get("categoryId"), ""), slug_by_name)

        amount = record.get("amount")
        if not isinstance(amount, int):
            raise SystemExit(f"record {record.get('_doc_id_rev')} has no integer amount")

        # `Record_<uuid>::1-<rev>` -> a stable TrackIt id.
        doc_id = record["_doc_id_rev"].split("::")[0]
        stable_id = doc_id.split("_", 1)[1]

        kept.append(
            {
                "id": stable_id,
                "amountCents": amount,
                "currency": "INR",
                "kind": kind,
                "account": account,
                "category": slug,
                "note": "",
                "spentAt": local_date(record["recordDate"], offset),
                "at": local_moment(record["recordDate"], offset),
                "source": "shortcut" if record.get("refObjects") else "manual",
                "createdAt": record["reservedCreatedAt"],
                "updatedAt": record["reservedUpdatedAt"],
                "_auto": bool(record.get("refObjects")),
            }
        )

    kept.sort(key=lambda row: (row["spentAt"], row["createdAt"]), reverse=True)

    # ---------------------------------------------------------------- app file
    # The app's own row shape, which is what its importer and exporter both speak:
    # money in paise, one absolute moment (`at`, epoch ms) that its day *and* its
    # clock are read from, the account it moved through, and the provenance of a
    # row a standing order generated. `title` is the category's own name because a
    # Wallet note is empty, and `spentAt` plus Wallet's two stamps ride along for
    # review — the importer ignores what it does not know.
    app_rows = [
        {
            "id": row["id"],
            "title": label_by_slug[row["category"]],
            "category": row["category"],
            "account": row["account"],
            "amountCents": row["amountCents"],
            "kind": row["kind"],
            "at": row["at"],
            "note": row["note"],
            "source": row["source"],
            "spentAt": row["spentAt"],
            "createdAt": row["createdAt"],
            "updatedAt": row["updatedAt"],
        }
        for row in kept
    ]
    with open(args.app_out, "w", encoding="utf-8") as handle:
        json.dump(app_rows, handle, indent=2)
        handle.write("\n")

    # --------------------------------------------------------------- the tables
    # The app's category tree and its accounts are written, not pasted. Both files
    # are the shape an import resolves against, and both are spliced rather than
    # regenerated whole: the prose around the tables is the app's, and this script
    # only owns the rows.
    repo_root = Path(__file__).resolve().parent.parent
    categories_file = repo_root / "app/src/lib/categories.ts"
    accounts_file = repo_root / "app/src/lib/accounts.ts"

    # The picker walks a group row, then that group's own row and its
    # subcategories — in table order, which is Wallet's own.
    group_lines = [
        f"  {{ id: {js_str(slug)}, label: {js_str(label)}, color: {js_str(colour)}, categories: ["
        + ", ".join(js_str(member) for _, member, system, group in CATEGORIES if group == slug and not system)
        + "] },"
        for slug, label, colour in GROUPS
    ]

    # The id/label/group rows the app's own `CATEGORIES` is built from. A plumbing
    # envelope has no group, so it carries its own id there: it still needs a row,
    # because a record can reference one and the app draws every row it holds.
    row_lines = [
        f"  [{js_str(slug)}, {js_str(name)}, {js_str(group or slug)}],"
        for name, slug, _, group in CATEGORIES
    ]
    system_lines = [f"  {js_str(slug)}," for _, slug, system, _ in CATEGORIES if system]

    # Wallet's accounts, in its own order: the first one is the primary, which is
    # where a row with no account lands.
    account_lines = []
    for index, account in enumerate(accounts.values()):
        line = (
            f"  {{ id: {js_str(account['slug'])}, name: {js_str(account['name'])},"
            f" openingCents: {account['opening']}"
        )
        account_lines.append(line + (", primary: true }," if index == 0 else " },"))

    # Each anchor stops past the `=`, so the table's own bracket is the first one
    # found rather than the one in the type (`Category[]`, `[id: string, ...]`).
    splice_array(categories_file, "export const CATEGORY_GROUPS: CategoryGroup[] = ", group_lines, len(GROUPS))
    splice_array(
        categories_file,
        "const ROWS: readonly (readonly [id: string, label: string, group: string])[] = ",
        row_lines,
        len(CATEGORIES),
    )
    splice_array(
        categories_file,
        "const SYSTEM = new Set(",
        system_lines,
        len([slug for _, slug, system, _ in CATEGORIES if system]),
    )
    splice_array(accounts_file, "export const ACCOUNTS: Account[] = ", account_lines, len(accounts))
    print(f"tables      {categories_file.relative_to(repo_root)}, {accounts_file.relative_to(repo_root)}")

    # ---------------------------------------------------------------- summary
    spent = sum(row["amountCents"] for row in kept if row["kind"] == "expense")
    received = sum(row["amountCents"] for row in kept if row["kind"] == "income")
    expenses = [row for row in kept if row["kind"] == "expense"]
    incomes = [row for row in kept if row["kind"] == "income"]
    months: dict[str, list[int]] = {}
    for row in expenses:
        bucket = months.setdefault(row["spentAt"][:7], [0, 0])
        bucket[0] += 1
        bucket[1] += row["amountCents"]

    # The accounts' opening balances plus everything imported since = the money
    # the owner actually has. TrackIt shows this on Home, so print it here
    # rather than inventing a number in two places.
    opening = sum(
        doc["initAmount"] for doc in docs if doc.get("reservedModelType") == "Account"
    )

    print(f"export      {args.export}")
    print(f"records     {len(records)} total, {len(kept)} imported")
    print("skipped     " + ", ".join(f"{count} {name}" for name, count in skipped.items()))
    if unassigned:
        print(f"unassigned  {unassigned} rows with no known account -> {FALLBACK_ACCOUNT}")
    print(f"spending    INR {spent / 100:,.2f} across {len(expenses)} expenses")
    print(f"income      INR {received / 100:,.2f} across {len(incomes)} entries")
    print(f"opening     INR {opening / 100:,.2f} in " + ", ".join(
        f"{doc['name']}" for doc in docs if doc.get("reservedModelType") == "Account"
    ))
    print(f"balance     INR {(opening + received - spent) / 100:,.2f}  (both accounts, opening)")
    # One line per account: both the slug the app's rows match on and the opening
    # figure the dashboard's balance counts up from, which is what accounts.ts
    # carries into the app.
    for account in accounts.values():
        rows = [row for row in kept if row["account"] == account["slug"]]
        received_here = sum(row["amountCents"] for row in rows if row["kind"] == "income")
        spent_here = sum(row["amountCents"] for row in rows if row["kind"] == "expense")
        print(
            f"  {account['slug']:<6}{len(rows):>3} rows   opening {account['opening']:>9}   "
            f"balance INR {(account['opening'] + received_here - spent_here) / 100:>10,.2f}"
            f"   ({account['name']})"
        )
    for month in sorted(months):
        count, cents = months[month]
        print(f"  {month}   {count:>3} expenses   INR {cents / 100:>10,.2f}")
    used = sorted({row["category"] for row in kept})
    unused = [slug for _, slug, _, _ in CATEGORIES if slug not in used]
    print(f"categories  {len(used)} used, {len(unused)} unused ({', '.join(unused)})")

    # The marker table, which is a promise rather than a print: a category with no
    # glyph is a fallback dot, and nothing else would say so.
    marker_count, marker_problems = check_markers(repo_root, [slug for _, slug, _, _ in CATEGORIES])
    if marker_problems:
        for problem in marker_problems:
            print(f"  ! markers: {problem}", file=sys.stderr)
    else:
        print(f"markers     {marker_count} category glyphs, one per category")

    # The groups the app walks, and the colour proof that they are right.
    for slug, label, colour in GROUPS:
        members = [member for _, member, system, group in CATEGORIES if group == slug and not system]
        print(f"group       {label:<22s} {colour}  {len(members)} categories: {', '.join(members)}")
    checked, problems = check_group_colors(docs, group_of_slug, slug_by_name)
    print(f"colours     {checked} categories checked against their group's colour")
    for problem in problems:
        print(f"  ! {problem}", file=sys.stderr)
    print(f"written     {args.app_out}")
    print(f"written     {accounts_file.relative_to(repo_root)}")
    return 0


