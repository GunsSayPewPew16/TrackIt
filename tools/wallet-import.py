ACCOUNT_LABEL = "{name} balance"


def account_slug(name: str) -> str:
    """"UPI" -> "upi", "Cash" -> "cash": a stable id from the owner's own name."""
    slug = "".join(c if c.isalnum() else "-" for c in name.lower()).strip("-")
    return slug or FALLBACK_ACCOUNT


def js_str(value: str) -> str:
    """A single-quoted JS/TS string literal, the house style of both files."""
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def slug_for(wallet_name: str, slug_by_name: dict[str, str]) -> str:
    """Map an export category name onto a TrackIt id, loudly if it is new."""
    slug = slug_by_name.get(wallet_name)
    if slug is None:
        print(f"  ! unknown category {wallet_name!r} -> {FALLBACK_SLUG}", file=sys.stderr)
        return FALLBACK_SLUG
    return slug


def local_date(iso: str, tz: timezone) -> str:
    """`2026-10-08T18:33:21.773Z` -> `2026-10-09` in the given offset."""
    stamp = iso.replace("Z", "+00:00")
    return datetime.fromisoformat(stamp).astimezone(tz).date().isoformat()


def load_docs(path: str) -> list[dict]:
    with open(path, encoding="utf-8") as handle:
        export = json.load(handle)

    # A Wallet export is `{ "<pouch user>": { "by-sequence": [...] } }`.
    db = next(iter(export.values()))
    return db["by-sequence"]


def check_group_colors(
    docs: list[dict],
    group_of_slug: dict[str, str | None],
    slug_by_name: dict[str, str],
) -> tuple[int, list[str]]:
    """Prove the table's groups against the colours in the export.

    Wallet paints every subcategory with its group's colour, so a category whose
    colour maps to a different group than the table claims is either a mistake in
    the table or a Wallet that groups things differently. Either way it is worth
    saying out loud rather than grouping the owner's money silently wrong.

    Returns how many categories could be checked, and every disagreement.
    """
    checked = 0
    problems: list[str] = []
    for doc in docs:
        if doc.get("reservedModelType") != "Category" or doc.get("_deleted"):
            continue
        colour = (doc.get("color") or "").upper()
        expected = GROUP_COLORS.get(colour)
        slug = slug_by_name.get(doc["name"])
        if not colour or expected is None or slug is None:
            continue
        checked += 1
        if group_of_slug.get(slug) != expected:
            problems.append(
                f"{doc['name']} is painted {colour} (group {expected}) "
                f"but the table puts it in {group_of_slug.get(slug)}"
            )
    return checked, problems


def account_table(docs: list[dict]) -> dict[str, dict]:
    """Wallet's own accounts, keyed by the id its records point at.

    A record's ``accountId`` is the account document's ``_doc_id_rev`` without
    its revision (``-Account_<uuid>``), so that prefix is the join key.
    """
    table: dict[str, dict] = {}
    for doc in docs:
        if doc.get("reservedModelType") != "Account":
            continue
        key = doc["_doc_id_rev"].split("::")[0]
        table[key] = {
            "slug": account_slug(doc["name"]),
            "name": doc["name"],
            "opening": doc["initAmount"],
        }
    return table


def splice_object(path: Path, anchor: str, rows: list[str], expected: int) -> None:
    """Rewrite the body of a `const NAME = { ... };` table, keeping the braces."""
    text = path.read_text(encoding="utf-8")
    start = text.index(anchor) + len(anchor)  # past the anchor, so `Category[]`
    open_brace = text.index("{", start)      # cannot be mistaken for the table
    close = re.search(r"\n\s*\};?\n", text[open_brace:])
    assert close, f"unterminated {anchor!r} in {path}"
    end = open_brace + close.start()  # the newline the closing brace sits on
    # A brace far below the first row means the table's own close was missed and
    # this is about to swallow code; refuse rather than corrupt the file.
    assert text[open_brace:end].count("\n") < expected + 3, (
        f"{path}: {anchor!r}'s closing brace looks too far away — refusing"
    )
    path.write_text(text[:open_brace] + "{\n" + "\n".join(rows) + text[end:])


def splice_array(path: Path, anchor: str, rows: list[str], expected: int) -> None:
    """Rewrite the body of an `export const NAME: T[] = [ ... ]` table."""
    text = path.read_text(encoding="utf-8")
    start = text.index(anchor) + len(anchor)  # past the anchor, so the type's own
    open_bracket = text.index("[", start)    # `[]` cannot be taken for the table
    close = re.search(r"\n\s*\];?\n", text[open_bracket:])
    assert close, f"unterminated {anchor!r} in {path}"
    end = open_bracket + close.start()  # the newline the closing bracket sits on
    assert text[open_bracket:end].count("\n") < expected + 3, (
        f"{path}: {anchor!r}'s closing bracket looks too far away — refusing"
    )
    path.write_text(text[:open_bracket] + "[\n" + "\n".join(rows) + text[end:])


def check_icons(repo_root: Path, slugs: list[str]) -> tuple[int, list[str]]:
    """Prove the two clients mark a category the same way — and mark all of them.

    ``tools/lucide-icons.py`` writes both tables from ``lucide-static``, and this
    is what catches either of them being edited afterwards: the mockup is
    hand-written HTML, and a table can be changed by hand. Same slugs, same
    shapes, or it says which category disagrees — and a category with no row in
    either table is named too, because the fallback dot is a placeholder rather
    than a marker. Only the tables' shape rows are read; the surrounding code is
    not.
    """
    tables = {
        "mockup": repo_root / "frontend/design/mockup.html",
        "app": repo_root / "frontend/src/lib/icons.tsx",
    }
    parsed: dict[str, dict[str, str]] = {}
    for name, file in tables.items():
        if not file.exists():
            return 0, [f"{file} is missing"]
        markup = file.read_text(encoding="utf-8")
        start = markup.index("CATEGORY_ICONS")
        close = re.search(r"\n\s*\};?\n", markup[start:])
        end = start + (close.end() if close else len(markup) - start)
        parsed[name] = dict(
            re.findall(r"'([^']+)':\s*'([^']+)',", markup[start:end])
        )

    problems: list[str] = []
    for slug in sorted(set(parsed["mockup"]) | set(parsed["app"])):
        their = parsed["mockup"].get(slug)
        ours = parsed["app"].get(slug)
        if their is None:
            problems.append(f"{slug} is marked in the app but not in the mockup")
        elif ours is None:
            problems.append(f"{slug} is marked in the mockup but not in the app")
        elif their != ours:
            problems.append(f"{slug} is drawn differently in the app: {ours}")
    for slug in slugs:
        if slug not in parsed["mockup"] and slug not in parsed["app"]:
            problems.append(f"{slug} has no marker in either table")
    return len(parsed["mockup"]), problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("export", help="wallet_unlocked_export.json")
    parser.add_argument("--app-out", default="tools/trackit-expenses.json", help="where to write the TrackIt array")
    parser.add_argument("--snippets", default="tools/mockup-snippets.txt", help="where to write the code snippets")
    parser.add_argument("--tz", default="+05:30", help="offset used to turn UTC recordDate into a local date")
    args = parser.parse_args()

    offset = datetime.strptime(args.tz, "%z").tzinfo if args.tz else timezone.utc
    assert offset is not None
    # Wallet repeats a handful of labels across sets — Child Support under three
    # of them, Lottery, gambling and Gifts under two — and a slug belongs to one
    # group, so the repeats carry their group in the id (`income-child-support`).
    # The export's own documents are the unqualified rows, and the rows already in
    # `trackit-expenses.json` name those slugs, so a repeat must never win a
    # name lookup: the plain table would hand "Child Support" to the Income row
    # (it is the last one), hence the explicit answer here.
    slug_by_name = {name: slug for name, slug, _, _ in CATEGORIES}
    slug_by_name.update(EXPORT_LABELS)
    label_by_slug = {slug: name for name, slug, _, _ in CATEGORIES}
    group_of_slug = {slug: group for _, slug, _, group in CATEGORIES}

    docs = load_docs(args.export)
    records = [doc for doc in docs if doc.get("reservedModelType") == "Record"]
    category_names = {
        doc["_doc_id_rev"].split("::")[0]: doc["name"]
        for doc in docs
        if doc.get("reservedModelType") == "Category"
    }
    accounts = account_table(docs)

    kept: list[dict] = []
    skipped = {"deleted": 0, "transfer": 0}
    unassigned = 0

    for record in records:
        if record.get("_deleted"):
            skipped["deleted"] += 1
            continue
        if record.get("transferId"):                      # money moved between own accounts
            skipped["transfer"] += 1
            continue
        kind = "expense" if record.get("type") == 1 else "income"

        held_by = accounts.get(record.get("accountId"))
        if held_by is None:
            unassigned += 1
            print(f"  ! account {record.get('accountId')!r} -> {FALLBACK_ACCOUNT}", file=sys.stderr)
        account = held_by["slug"] if held_by else FALLBACK_ACCOUNT

        slug = slug_for(category_names.get(record.get("categoryId"), ""), slug_by_name)

        amount = record.get("amount")
        if not isinstance(amount, int):
            raise SystemExit(f"record {record.get('_doc_id_rev')} has no integer amount")

        # `Record_<uuid>::1-<rev>` -> a stable TrackIt id.
        doc_id = record["_doc_id_rev"].split("::")[0]
        stable_id = doc_id.split("_", 1)[1]

        kept.append(
            {
                "id": stable_id,
                "amountCents": amount,
                "currency": "INR",
                "kind": kind,
                "account": account,
                "category": slug,
                "note": "",
                "spentAt": local_date(record["recordDate"], offset),
                "source": "shortcut" if record.get("refObjects") else "manual",
                "createdAt": record["reservedCreatedAt"],
                "updatedAt": record["reservedUpdatedAt"],
                "_auto": bool(record.get("refObjects")),
            }
        )

    kept.sort(key=lambda row: (row["spentAt"], row["createdAt"]), reverse=True)

    # ---------------------------------------------------------------- app file
    # `account` stays out: it is the mockup's (see the docstring). The app's
    # Expense type has no such field, and its import drops what it does not know.
    app_rows = [
        {key: value for key, value in row.items() if not key.startswith("_") and key != "account"}
        for row in kept
    ]
    with open(args.app_out, "w", encoding="utf-8") as handle:
        json.dump(app_rows, handle, indent=2)
        handle.write("\n")

    # ---------------------------------------------------------------- snippets
    # The mockup's balance card walks these in order, so Wallet's own order wins.
    # `name` is the short one the modal's toggle prints; `label` is what the
    # balance card writes above the figure.
    account_fields = [
        (
            js_str(account["slug"]) + ",",
            js_str(account["name"]) + ",",
            js_str(ACCOUNT_LABEL.format(name=account["name"])) + ",",
            account["opening"],
            account["name"],
        )
        for account in accounts.values()
    ]
    account_slug_width = max((len(slug) for slug, _, _, _, _ in account_fields), default=0) + 1
    account_name_width = max((len(name) for _, name, _, _, _ in account_fields), default=0) + 1
    account_label_width = max((len(label) for _, _, label, _, _ in account_fields), default=0) + 1
    account_lines = [
        f"      {{ slug: {slug:<{account_slug_width}} name: {name:<{account_name_width}}"
        f" label: {label:<{account_label_width}} opening: {opening} }},   // {plain}: ₹{opening / 100:,.2f}"
        for slug, name, label, opening, plain in account_fields
    ]

    # The mockup's picker walks a group row, then that group's own row and its
    # subcategories — in table order, which is Wallet's own.
    group_slug_width = max(len(js_str(slug)) + 1 for slug, _, _ in GROUPS) + 1
    group_label_width = max(len(js_str(label)) + 1 for _, label, _ in GROUPS) + 1
    group_lines = [
        f"      {{ slug: {js_str(slug) + ',':<{group_slug_width}} label: {js_str(label) + ',':<{group_label_width}}"
        f" color: '{colour}', categories: ["
        + ", ".join(js_str(member) for _, member, system, group in CATEGORIES if group == slug and not system)
        + "] },"
        for slug, label, colour in GROUPS
    ]

    # The app walks the same groups, in its own house style: `id` where the
    # mockup says `slug`, and a typed array rather than a bare literal.
    app_group_lines = [
        f"  {{ id: {js_str(slug) + ',':<{group_slug_width}} label: {js_str(label) + ',':<{group_label_width}}"
        f" color: '{colour}', categories: ["
        + ", ".join(js_str(member) for _, member, system, group in CATEGORIES if group == slug and not system)
        + "] },"
        for slug, label, colour in GROUPS
    ]

    width = max(len(slug) for _, slug, _, _ in CATEGORIES)
    # Keys are quoted: several slugs contain a dash and would not parse bare.
    meta_lines = [
        f"      {(js_str(slug) + ':'):<{width + 3}} {{ label: {js_str(name)}"
        + (", sys: true }," if system else " },")
        for name, slug, system, _ in CATEGORIES
    ]
    ts_lines = [
        f"  {{ id: {js_str(slug)}, label: {js_str(name)}"
        + (", system: true }," if system else " },")
        for name, slug, system, _ in CATEGORIES
    ]
    row_lines = [
        "      {{ id: {id}, title: {title}, kind: '{kind}', account: '{account}', category: '{category}', cents: {cents}, auto: {auto}, date: '{date}' }},".format(
            id=index + 1,
            title=js_str(label_by_slug[row["category"]]),
            kind=row["kind"],
            account=row["account"],
            category=row["category"],
            cents=row["amountCents"],
            auto="true" if row["_auto"] else "false",
            date=row["spentAt"],
        )
        for index, row in enumerate(kept)
    ]

    snippets = "\n".join(
        [
            "// ---- frontend/design/mockup.html: const CATEGORY_META = { ... } ----",
            *meta_lines,
            "",
            "// ---- frontend/design/mockup.html: const ACCOUNTS = [ ... ] ----",
            *account_lines,
            "",
            "// ---- frontend/design/mockup.html: const CATEGORY_GROUPS = [ ... ] ----",
            *group_lines,
            "",
            "// ---- frontend/src/lib/types.ts: export const CATEGORIES: Category[] = [ ... ] ----",
            *ts_lines,
            "",
            "// ---- frontend/src/lib/types.ts: export const CATEGORY_GROUPS: CategoryGroup[] = [ ... ] ----",
            *app_group_lines,
            "",
            "// ---- frontend/design/mockup.html: const importedExpenses = () => [ ... ] ----",
            *row_lines,
            "",
        ]
    )
    with open(args.snippets, "w", encoding="utf-8") as handle:
        handle.write(snippets)

    # --------------------------------------------------------------- the clients
    # The tables are written into both clients rather than pasted: the mockup is
    # hand-written HTML and the app's list is a typed literal, and a hand-paste of
    # ninety rows is exactly where a label or a group quietly drifts. The snippets
    # file above stays as the reviewable copy of the same text.
    repo_root = Path(__file__).resolve().parent.parent
    mockup = repo_root / "frontend/design/mockup.html"
    app_types = repo_root / "frontend/src/lib/types.ts"
    # Each anchor stops at the `=`: searching on from there finds the table's own
    # brace or bracket rather than the one in the type (`Category[]`).
    splice_object(mockup, "const CATEGORY_META = ", meta_lines, len(CATEGORIES))
    splice_array(mockup, "const CATEGORY_GROUPS = ", group_lines, len(GROUPS))
    splice_array(app_types, "export const CATEGORIES: Category[] = ", ts_lines, len(CATEGORIES))
    splice_array(
        app_types, "export const CATEGORY_GROUPS: CategoryGroup[] = ", app_group_lines, len(GROUPS)
    )
    print(f"tables      {mockup.relative_to(repo_root)}, {app_types.relative_to(repo_root)}")

    # ---------------------------------------------------------------- summary
    spent = sum(row["amountCents"] for row in kept if row["kind"] == "expense")
    received = sum(row["amountCents"] for row in kept if row["kind"] == "income")
    expenses = [row for row in kept if row["kind"] == "expense"]
    incomes = [row for row in kept if row["kind"] == "income"]
    months: dict[str, list[int]] = {}
    for row in expenses:
        bucket = months.setdefault(row["spentAt"][:7], [0, 0])
        bucket[0] += 1
        bucket[1] += row["amountCents"]

    # The accounts' opening balances plus everything imported since = the money
    # the owner actually has. TrackIt shows this on Home, so print it here
    # rather than inventing a number in two places.
    opening = sum(
        doc["initAmount"] for doc in docs if doc.get("reservedModelType") == "Account"
    )

    print(f"export      {args.export}")
    print(f"records     {len(records)} total, {len(kept)} imported")
    print("skipped     " + ", ".join(f"{count} {name}" for name, count in skipped.items()))
    if unassigned:
        print(f"unassigned  {unassigned} rows with no known account -> {FALLBACK_ACCOUNT}")
    print(f"spending    INR {spent / 100:,.2f} across {len(expenses)} expenses")
    print(f"income      INR {received / 100:,.2f} across {len(incomes)} entries")
    print(f"opening     INR {opening / 100:,.2f} in " + ", ".join(
        f"{doc['name']}" for doc in docs if doc.get("reservedModelType") == "Account"
    ))
    print(f"balance     INR {(opening + received - spent) / 100:,.2f}  (OPENING_BALANCE_CENTS = {opening})")
    # One line per account: the mockup's balance card needs both the slug it
    # matches rows on and the opening figure it starts counting from.
    for account in accounts.values():
        rows = [row for row in kept if row["account"] == account["slug"]]
        received_here = sum(row["amountCents"] for row in rows if row["kind"] == "income")
        spent_here = sum(row["amountCents"] for row in rows if row["kind"] == "expense")
        print(
            f"  {account['slug']:<6}{len(rows):>3} rows   opening {account['opening']:>9}   "
            f"balance INR {(account['opening'] + received_here - spent_here) / 100:>10,.2f}"
            f"   ({account['name']})"
        )
    for month in sorted(months):
        count, cents = months[month]
        print(f"  {month}   {count:>3} expenses   INR {cents / 100:>10,.2f}")
    used = sorted({row["category"] for row in kept})
    unused = [slug for _, slug, _, _ in CATEGORIES if slug not in used]
    print(f"categories  {len(used)} used, {len(unused)} unused ({', '.join(unused)})")

    # The two clients' icon tables, which are a promise rather than a print.
    icon_count, icon_problems = check_icons(repo_root, [slug for _, slug, _, _ in CATEGORIES])
    if icon_problems:
        for problem in icon_problems:
            print(f"  ! icons: {problem}", file=sys.stderr)
    else:
        print(f"icons       {icon_count} markers, identical in the mockup and the app")

    # The groups the pickers walk, and the colour proof that they are right.
    for slug, label, colour in GROUPS:
        members = [member for _, member, system, group in CATEGORIES if group == slug and not system]
        print(f"group       {label:<22s} {colour}  {len(members)} categories: {', '.join(members)}")
    checked, problems = check_group_colors(docs, group_of_slug, slug_by_name)
    print(f"colours     {checked} categories checked against their group's colour")
    for problem in problems:
        print(f"  ! {problem}", file=sys.stderr)
    print(f"written     {args.app_out}")
    print(f"written     {args.snippets}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
