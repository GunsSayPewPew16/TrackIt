#!/usr/bin/env python3
"""Convert a Wallet (BudgetBakers) PouchDB export into TrackIt data.

Usage
-----
    python3 tools/wallet-import.py ~/Downloads/wallet_unlocked_export.json \
        --app-out tools/trackit-expenses.json \
        --snippets tools/mockup-snippets.txt

What it does
------------
Wallet records are read from the export's ``by-sequence`` list and turned into
the two shapes TrackIt understands:

* ``--app-out``  a bare JSON array of ``Expense`` rows, exactly what
  ``src/components/SettingsScreen.tsx`` imports and exports. Import it in the
  app with **Settings -> Import JSON**.
* ``--snippets`` the same data as a JS array literal, plus the category tables
  for ``design/mockup.html`` (``CATEGORY_META``) and ``src/lib/types.ts``
  (``CATEGORIES``). All three are printed from the one table below, so the
  ids, labels and emoji cannot drift apart.

Decisions baked in (change them here, not by hand)
--------------------------------------------------
* **Expenses only.** Wallet ``type == 1`` is spending; ``type == 0`` is income
  (allowance, money friends paid back) and internal transfers carry a
  ``transferId``. TrackIt models spending, so both are skipped and counted in
  the summary. Soft-deleted rows (``_deleted``) are skipped too.
* **Amounts are already rupees.** Wallet stores money as integer minor units
  and the export's referential currency is INR, so ``amount`` is paise and maps
  straight onto TrackIt's ``amountCents``. No rate is applied; TrackIt only has
  to *display* INR (``DEFAULT_CURRENCY``).
* **Dates are local, not UTC.** Wallet writes ``recordDate`` in UTC. India is a
  fixed ``+05:30`` with no DST, so the default ``--tz +05:30`` turns a 00:03 IST
  entry (18:33Z the day before) into the day the owner actually spent it.
* **Stable ids.** The Wallet document id (``Record_<uuid>``) becomes the
  TrackIt id, so re-importing the same export updates rows instead of
  duplicating them.
* **Rows generated by a standing order keep that provenance** as
  ``source: "shortcut"`` / ``auto: true``, which is what draws the AUTO badge.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timedelta, timezone

# --------------------------------------------------------------------------
# The one category table. `wallet_name` is matched against the export
# verbatim; `slug` is the TrackIt id, `emoji` the icon, and `system` marks the
# six Wallet envelopes that are plumbing rather than owner-facing categories —
# they render if a record references them but are hidden from pickers.
# --------------------------------------------------------------------------
CATEGORIES = [
    ("Restaurant, fast-food", "restaurant", "🍽️", False),
    ("Food & Drinks", "food-drinks", "🍔", False),
    ("Bar, cafe", "bar-cafe", "🍸", False),
    ("Stationery, tools", "stationery", "📐", False),
    ("Books, audio, subscriptions", "books-subs", "🔖", False),
    ("Public transport", "public-transport", "🚋", False),
    ("Phone, cell phone", "phone", "📱", False),
    ("Long distance", "long-distance", "✈️", False),
    ("Mobile Recharge", "mobile-recharge", "📶", False),
    ("Health and beauty", "health-beauty", "🧴", False),
    ("Wellness, beauty", "wellness", "🌸", False),
    ("Culture, sport events", "culture-sport", "🎭", False),
    ("Education, development", "education", "🎓", False),
    ("Child Support", "child-support", "👶", False),
    ("Life & Entertainment", "life-entertainment", "🎉", False),
    ("Friends", "friends", "🤝", False),
    ("Allowance", "allowance", "💵", False),
    ("Debts", "debts", "🏦", True),
    ("Transfer, withdraw", "transfer", "🔁", True),
    ("Shopping list", "shopping-list", "🧺", True),
    ("Wallet - OneClick record", "oneclick", "✨", True),
    ("Automatic bank statements reading", "bank-statements", "📰", True),
    ("Unknown", "unknown", "❓", True),
]

FALLBACK_SLUG = "unknown"


def js_str(value: str) -> str:
    """A single-quoted JS/TS string literal, the house style of both files."""
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def slug_for(wallet_name: str, slug_by_name: dict[str, str]) -> str:
    """Map an export category name onto a TrackIt id, loudly if it is new."""
    slug = slug_by_name.get(wallet_name)
    if slug is None:
        print(f"  ! unknown category {wallet_name!r} -> {FALLBACK_SLUG}", file=sys.stderr)
        return FALLBACK_SLUG
    return slug


def local_date(iso: str, tz: timezone) -> str:
    """`2026-10-08T18:33:21.773Z` -> `2026-10-09` in the given offset."""
    stamp = iso.replace("Z", "+00:00")
    return datetime.fromisoformat(stamp).astimezone(tz).date().isoformat()


def load_docs(path: str) -> list[dict]:
    with open(path, encoding="utf-8") as handle:
        export = json.load(handle)

    # A Wallet export is `{ "<pouch user>": { "by-sequence": [...] } }`.
    db = next(iter(export.values()))
    return db["by-sequence"]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("export", help="wallet_unlocked_export.json")
    parser.add_argument("--app-out", default="tools/trackit-expenses.json", help="where to write the TrackIt array")
    parser.add_argument("--snippets", default="tools/mockup-snippets.txt", help="where to write the code snippets")
    parser.add_argument("--tz", default="+05:30", help="offset used to turn UTC recordDate into a local date")
    args = parser.parse_args()

    offset = datetime.strptime(args.tz, "%z").tzinfo if args.tz else timezone.utc
    assert offset is not None
    slug_by_name = {name: slug for name, slug, _, _ in CATEGORIES}
    label_by_slug = {slug: name for name, slug, _, _ in CATEGORIES}

    docs = load_docs(args.export)
    records = [doc for doc in docs if doc.get("reservedModelType") == "Record"]
    category_names = {
        doc["_doc_id_rev"].split("::")[0]: doc["name"]
        for doc in docs
        if doc.get("reservedModelType") == "Category"
    }

    kept: list[dict] = []
    skipped = {"deleted": 0, "income": 0, "transfer": 0}

    for record in records:
        if record.get("_deleted"):
            skipped["deleted"] += 1
            continue
        if record.get("type") != 1:                      # 0 == income
            skipped["income"] += 1
            continue
        if record.get("transferId"):                      # money moved between own accounts
            skipped["transfer"] += 1
            continue

        slug = slug_for(category_names.get(record.get("categoryId"), ""), slug_by_name)

        amount = record.get("amount")
        if not isinstance(amount, int):
            raise SystemExit(f"record {record.get('_doc_id_rev')} has no integer amount")

        # `Record_<uuid>::1-<rev>` -> a stable TrackIt id.
        doc_id = record["_doc_id_rev"].split("::")[0]
        stable_id = doc_id.split("_", 1)[1]

        kept.append(
            {
                "id": stable_id,
                "amountCents": amount,
                "currency": "INR",
                "category": slug,
                "note": "",
                "spentAt": local_date(record["recordDate"], offset),
                "source": "shortcut" if record.get("refObjects") else "manual",
                "createdAt": record["reservedCreatedAt"],
                "updatedAt": record["reservedUpdatedAt"],
                "_auto": bool(record.get("refObjects")),
            }
        )

    kept.sort(key=lambda row: (row["spentAt"], row["createdAt"]), reverse=True)

    # ---------------------------------------------------------------- app file
    app_rows = [{key: value for key, value in row.items() if not key.startswith("_")} for row in kept]
    with open(args.app_out, "w", encoding="utf-8") as handle:
        json.dump(app_rows, handle, indent=2)
        handle.write("\n")

    # ---------------------------------------------------------------- snippets
    width = max(len(slug) for _, slug, _, _ in CATEGORIES)
    # Keys are quoted: several slugs contain a dash and would not parse bare.
    meta_lines = [
        f"      {(js_str(slug) + ':'):<{width + 3}} {{ emoji: '{emoji}', label: {js_str(name)}"
        + (", sys: true }," if system else " },")
        for name, slug, emoji, system in CATEGORIES
    ]
    ts_lines = [
        f"  {{ id: {js_str(slug)}, label: {js_str(name)}, emoji: '{emoji}'"
        + (", system: true }," if system else " },")
        for name, slug, emoji, system in CATEGORIES
    ]
    row_lines = [
        "      {{ id: {id}, title: {title}, category: '{category}', cents: {cents}, auto: {auto}, date: '{date}' }},".format(
            id=index + 1,
            title=js_str(label_by_slug[row["category"]]),
            category=row["category"],
            cents=row["amountCents"],
            auto="true" if row["_auto"] else "false",
            date=row["spentAt"],
        )
        for index, row in enumerate(kept)
    ]

    snippets = "\n".join(
        [
            "// ---- design/mockup.html: const CATEGORY_META = { ... } ----",
            *meta_lines,
            "",
            "// ---- src/lib/types.ts: export const CATEGORIES: Category[] = [ ... ] ----",
            *ts_lines,
            "",
            "// ---- design/mockup.html: const importedExpenses = () => [ ... ] ----",
            *row_lines,
            "",
        ]
    )
    with open(args.snippets, "w", encoding="utf-8") as handle:
        handle.write(snippets)

    # ---------------------------------------------------------------- summary
    total = sum(row["amountCents"] for row in kept)
    months: dict[str, list[int]] = {}
    for row in kept:
        bucket = months.setdefault(row["spentAt"][:7], [0, 0])
        bucket[0] += 1
        bucket[1] += row["amountCents"]

    print(f"export      {args.export}")
    print(f"records     {len(records)} total, {len(kept)} imported")
    print("skipped     " + ", ".join(f"{count} {name}" for name, count in skipped.items()))
    print(f"total       INR {total / 100:,.2f} across {len(kept)} expenses")
    for month in sorted(months):
        count, cents = months[month]
        print(f"  {month}   {count:>3} expenses   INR {cents / 100:>10,.2f}")
    used = sorted({row["category"] for row in kept})
    unused = [slug for _, slug, _, _ in CATEGORIES if slug not in used]
    print(f"categories  {len(used)} used, {len(unused)} unused ({', '.join(unused)})")
    print(f"written     {args.app_out}")
    print(f"written     {args.snippets}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
