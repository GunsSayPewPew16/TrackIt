#!/usr/bin/env python3
"""Convert a Wallet (BudgetBakers) PouchDB export into TrackIt data.

Usage
-----
    python3 tools/wallet-import.py ~/Downloads/wallet_unlocked_export.json \
        --app-out tools/trackit-expenses.json \
        --snippets tools/mockup-snippets.txt

What it does
------------
Wallet records are read from the export's ``by-sequence`` list and turned into
the two shapes TrackIt understands:

* ``--app-out``  a bare JSON array of ``Expense`` rows, exactly what
  ``frontend/src/components/SettingsScreen.tsx`` imports and exports. Import it in the
  app with **Settings -> Import JSON**.
* ``--snippets`` the same data as a JS array literal, plus every category table
  as text, for review.

The category tables are not pasted by hand any more: the mockup's
``CATEGORY_META`` and ``CATEGORY_GROUPS``, and the app's ``CATEGORIES`` and
``CATEGORY_GROUPS``, are written straight into ``frontend/design/mockup.html`` and
``frontend/src/lib/types.ts`` from the one table below, so the ids, labels and
groups cannot drift apart. The markers are the other half of that promise:
``tools/lucide-icons.py`` writes both
clients' marker tables out of ``lucide-static`` (the app's chrome comes from the same
script), and ``check_icons`` here proves the two tables agree
*and* that every category has one, which is what catches a table edited by hand.
Every run also proves the groups against the colours in the export
(``check_group_colors``), because Wallet ships no list of its own.

Decisions baked in (change them here, not by hand)
--------------------------------------------------
* **Expenses and income, not transfers.** Wallet ``type == 1`` is spending and
  ``type == 0`` is income (allowance, money friends paid back); both arrive as
  ``kind``, which is what keeps income out of the spending totals. Internal
  transfers carry a ``transferId``: money merely moved between the owner's own
  accounts, so they are skipped and counted in the summary. Soft-deleted rows
  (``_deleted``) are skipped too.
* **No ``kind`` means an expense.** Rows written before income existed (and any
  hand-written file) keep working, in the app and in the mockup.
* **Amounts are already rupees.** Wallet stores money as integer minor units
  and the export's referential currency is INR, so ``amount`` is paise and maps
  straight onto TrackIt's ``amountCents``. No rate is applied; TrackIt only has
  to *display* INR (``DEFAULT_CURRENCY``).
* **Dates are local, not UTC.** Wallet writes ``recordDate`` in UTC. India is a
  fixed ``+05:30`` with no DST, so the default ``--tz +05:30`` turns a 00:03 IST
  entry (18:33Z the day before) into the day the owner actually spent it.
* **Stable ids.** The Wallet document id (``Record_<uuid>``) becomes the
  TrackIt id, so re-importing the same export updates rows instead of
  duplicating them.
* **Rows generated by a standing order keep that provenance** as
  ``source: "shortcut"`` / ``auto: true``, which is what draws the AUTO badge.
* **Which account the money moved through** rides along as ``account``: Wallet's
  ``accountId`` resolved against its own ``Account`` documents (UPI, Cash). It is
  what lets the mockup's Home show a real balance per account instead of one
  total. TrackIt's app-side ``Expense`` type has no ``account`` yet, so
  ``--app-out`` leaves the key out rather than writing a field the app's import
  would silently drop; the mockup row literals keep it.
* **No ``account`` means the primary account**, exactly the way no ``kind`` means
  an expense: rows from a hand-written file, or from a version of the mockup that
  predates accounts, land on UPI instead of vanishing from both balances.
"""

