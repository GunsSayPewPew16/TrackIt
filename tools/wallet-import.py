#!/usr/bin/env python3
"""Convert a Wallet (BudgetBakers) PouchDB export into TrackIt data.

Usage
-----
    python3 tools/wallet-import.py ~/Downloads/wallet_unlocked_export.json

What it does
------------
Wallet records are read from the export's ``by-sequence`` list and turned into
the app's own row shape, and the app's own tables are written from the single
``CATEGORIES`` table below:

* ``--app-out``  a bare JSON array of ledger rows — the shape the app's data
  panel imports and exports, so what this writes can be handed straight to it.
* ``app/src/lib/categories.ts``  the owner's whole category tree: the groups, the
  ``id``/``label``/``group`` rows, and the six plumbing envelopes that render but
  are never offered.
* ``app/src/lib/accounts.ts``  Wallet's own two accounts and the balance each one
  started from, which is what the dashboard counts up from.

Neither table is pasted by hand: a paste of ninety rows is exactly where a label
or a group quietly drifts. The markers are the other half of that promise —
``tools/lucide-icons.py`` writes the app's marker table out of ``lucide-static``,
and ``check_markers`` here proves every category has one, which is what catches a
table edited by hand. Every run also proves the groups against the colours in the
export (``check_group_colors``), because Wallet ships no list of its own.

The app reads a Wallet export directly as well — its data panel takes this same
file — so this script is the *reviewable* path: what it prints is what it found,
and what it writes is what an import produces. Envelopes are the one thing it does
not carry over: a budget exists only in the export's own ``Budget`` documents, and
the importer reads those from the file itself.

Decisions baked in (change them here, not by hand)
--------------------------------------------------
* **Expenses and income, not transfers.** Wallet ``type == 1`` is spending and
  ``type == 0`` is income (allowance, money friends paid back); both arrive as
  ``kind``, which is what keeps income out of the spending totals. Internal
  transfers carry a ``transferId``: money merely moved between the owner's own
  accounts, so they are skipped and counted in the summary. Soft-deleted rows
  (``_deleted``) are skipped too.
* **No ``kind`` means an expense.** Rows written before income existed (and any
  hand-written file) keep working in the app and in an import.
* **Amounts are already rupees.** Wallet stores money as integer minor units
  and the export's referential currency is INR, so ``amount`` is paise and maps
  straight onto TrackIt's ``amountCents``. No rate is applied; TrackIt only has
  to *display* INR (``DEFAULT_CURRENCY``).
* **Dates are local, not UTC, and a row keeps its clock.** Wallet writes
  ``recordDate`` in UTC. India is a fixed ``+05:30`` with no DST, so the default
  ``--tz +05:30`` turns a 00:03 IST
  entry (18:33Z the day before) into the day the owner actually spent it.
* **Stable ids.** The Wallet document id (``Record_<uuid>``) becomes the
  TrackIt id, so re-importing the same export updates rows instead of
  duplicating them.
* **Rows generated by a standing order keep that provenance** as
  ``source: "shortcut"``, which is what tells a machine-written row from one the
  owner typed.
* **Which account the money moved through** rides along as ``account``: Wallet's
  ``accountId`` resolved against its own ``Account`` documents (UPI, Cash), whose
  opening balances are written into ``app/src/lib/accounts.ts``. That is what the
  dashboard's balance counts up from.
* **No ``account`` means the primary account**, exactly the way no ``kind`` means
  an expense: rows from a hand-written file land on UPI instead of vanishing from
  the balance.
"""

