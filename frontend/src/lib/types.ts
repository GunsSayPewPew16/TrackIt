/** Shared domain types for TrackIt. */

/**
 * Where a row came from. `upi` is a row logged by the scan-and-pay flow, which
 * is worth marking: it is the one row whose amount the owner confirmed against
 * a payment they were about to make, and the one that may never have been paid.
 */
export type ExpenseSource = 'manual' | 'shortcut' | 'upi'

/** Spending or income. Income is money in, and never counts as spending. */
export type ExpenseKind = 'expense' | 'income'

export type Expense = {
  id: string
  /** Money is stored as integer minor units (cents) to avoid float drift. */
  amountCents: number
  currency: string
  kind: ExpenseKind
  category: string
  note: string
  /** Local calendar date the money was spent, as `YYYY-MM-DD`. */
  spentAt: string
  source: ExpenseSource
  createdAt: string
  updatedAt: string
}

export type Category = {
  id: string
  label: string
  /** Wallet's plumbing envelopes: renderable, but never offered as a choice. */
  system?: boolean
}

/**
 * A Wallet category group: the row the picker shows, and the categories that
 * open under it. `color` is the group's own paint in Wallet, which is what the
 * marker on every row of the group is drawn in.
 */
export type CategoryGroup = {
  id: string
  label: string
  color: string
  /** The group's own category first — the row above Wallet's "SUBCATEGORIES". */
  categories: string[]
}

