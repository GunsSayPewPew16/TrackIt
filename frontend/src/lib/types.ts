/** Which group a category hangs under, for the colour its marker is drawn in. */
const GROUP_OF_CATEGORY = new Map<string, CategoryGroup>(
  CATEGORY_GROUPS.flatMap((group) =>
    group.categories.map((id) => [id, group] as const),
  ),
)

/**
 * The group a category belongs to. Wallet's plumbing envelopes belong to none,
 * so they come back `undefined` and are marked in the neutral tone instead.
 */
export const groupFor = (id: string): CategoryGroup | undefined =>
  GROUP_OF_CATEGORY.get(id)

export const DEFAULT_CATEGORY = 'unknown'

export function categoryFor(id: string): Category {
  const known = CATEGORIES.find((category) => category.id === id)
  if (known) return known
  return (
    CATEGORIES.find((category) => category.id === DEFAULT_CATEGORY) ?? CATEGORIES[0]
  )
}

