/** Everything the owner can pick. Wallet's own envelopes stay out. */
export const PICKABLE_CATEGORIES = CATEGORIES.filter((category) => !category.system)

export const DEFAULT_CATEGORY = 'unknown'

export function categoryFor(id: string): Category {
  const known = CATEGORIES.find((category) => category.id === id)
  if (known) return known
  return (
    CATEGORIES.find((category) => category.id === DEFAULT_CATEGORY) ?? CATEGORIES[0]
  )
}

