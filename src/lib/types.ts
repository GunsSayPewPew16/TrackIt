/** Shared domain types for TrackIt. */

export type ExpenseSource = 'manual' | 'shortcut'

export type Expense = {
  id: string
  /** Money is stored as integer minor units (cents) to avoid float drift. */
  amountCents: number
  currency: string
  category: string
  note: string
  /** Local calendar date the money was spent, as `YYYY-MM-DD`. */
  spentAt: string
  source: ExpenseSource
  createdAt: string
  updatedAt: string
}

export type Category = {
  id: string
  label: string
  emoji: string
  /** Wallet's plumbing envelopes: renderable, but never offered as a choice. */
  system?: boolean
}

